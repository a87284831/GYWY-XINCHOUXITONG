<?php

namespace App\Invoice\Issuers;

use Illuminate\Support\Facades\Storage;

class FakeIssuer implements InvoiceIssuer
{
    public function name(): string
    {
        return 'fake';
    }

    public function issue(array $request, object $accountSet): array
    {
        $invoiceNo = '26' . now()->format('ymd') . str_pad((string) random_int(0, 999999999999), 12, '0', STR_PAD_LEFT);
        $orderNo = 'SIM-' . $request['request_no'];
        $dir = 'invoice/' . $this->safe($accountSet->code) . '/' . now()->format('Ym') . '/' . $request['id'];
        $path = $dir . '/invoice-' . $invoiceNo . '.pdf';

        Storage::disk((string) config('invoice.storage.disk', 'local'))->put($path, $this->pdf([
            'SIMULATED DIGITAL INVOICE (NOT A REAL INVOICE)',
            'Invoice No: ' . $invoiceNo,
            'Order No: ' . $orderNo,
            'Seller: ' . $request['seller_name_snapshot'],
            'Seller Tax No: ' . $request['seller_tax_no_snapshot'],
            'Buyer: ' . $request['title'],
            'Amount (incl. tax): CNY ' . number_format((float) $request['verified_amount'], 2),
            'Issued At: ' . now()->format('Y-m-d H:i:s'),
            'Generated by local fake issuer. Nuonuo credentials are not configured.',
        ]));

        // 模拟 OFD：生成带 OFD 目录结构的最小压缩包，便于业主端验证 OFD 下载入口
        $ofdPath = $dir . '/invoice-' . $invoiceNo . '.ofd';
        $ofd = $this->ofdPackage($invoiceNo, [
            'SIMULATED OFD (NOT A REAL INVOICE)',
            'Invoice No: ' . $invoiceNo,
            'Seller: ' . $request['seller_name_snapshot'],
            'Buyer: ' . $request['title'],
            'Amount (incl. tax): CNY ' . number_format((float) $request['verified_amount'], 2),
        ]);
        if ($ofd !== null) {
            Storage::disk((string) config('invoice.storage.disk', 'local'))->put($ofdPath, $ofd);
        } else {
            $ofdPath = null;
        }

        return [
            'ok' => true,
            'invoice_no' => $invoiceNo,
            'order_no' => $orderNo,
            'pdf_path' => $path,
            'ofd_path' => $ofdPath,
            'simulated' => true,
            'raw' => ['provider' => 'fake'],
        ];
    }

    public function redFlush(array $request, object $accountSet, string $reason): array
    {
        return [
            'ok' => true,
            'red_confirm_no' => 'SIMRC' . now()->format('YmdHis') . random_int(100, 999),
            'red_invoice_no' => 'SIMRI' . now()->format('YmdHis') . random_int(100, 999),
            'simulated' => true,
            'raw' => ['provider' => 'fake', 'reason' => $reason],
        ];
    }

    private function safe(string $value): string
    {
        return preg_replace('/[^A-Za-z0-9_-]/', '_', $value) ?: 'default';
    }

    /**
     * 生成最小 OFD 压缩包（仅本地模拟，不含真实签章），用于验证 OFD 下载链路。
     */
    private function ofdPackage(string $invoiceNo, array $lines): ?string
    {
        if (!class_exists(\ZipArchive::class)) {
            return null;
        }
        $tmp = tempnam(sys_get_temp_dir(), 'ofd');
        if ($tmp === false) {
            return null;
        }
        $zip = new \ZipArchive();
        if ($zip->open($tmp, \ZipArchive::CREATE | \ZipArchive::OVERWRITE) !== true) {
            @unlink($tmp);
            return null;
        }
        $esc = fn (string $s) => htmlspecialchars($s, ENT_XML1 | ENT_QUOTES, 'UTF-8');
        $text = '';
        $y = 30;
        foreach ($lines as $line) {
            $text .= '<ofd:TextObject ID="' . md5($line) . '" Boundary="20 ' . $y . ' 190 10" Font="1" Size="9">'
                . '<ofd:TextCode X="0" Y="0">' . $esc($line) . '</ofd:TextCode></ofd:TextObject>';
            $y += 12;
        }
        $zip->addFromString('OFD.xml', '<?xml version="1.0" encoding="UTF-8"?>'
            . '<ofd:OFD xmlns:ofd="http://www.ofdspec.org/2016" DocType="OFD" Version="1.0">'
            . '<ofd:DocBody><ofd:DocInfo><ofd:DocID>' . $esc($invoiceNo) . '</ofd:DocID>'
            . '<ofd:Creator>Local Fake Issuer</ofd:Creator><ofd:CreatorVersion>1.0</ofd:CreatorVersion></ofd:DocInfo>'
            . '<ofd:DocRoot>Doc_0/Document.xml</ofd:DocRoot></ofd:DocBody></ofd:OFD>');
        $zip->addFromString('Doc_0/Document.xml', '<?xml version="1.0" encoding="UTF-8"?>'
            . '<ofd:Document xmlns:ofd="http://www.ofdspec.org/2016">'
            . '<ofd:CommonData><ofd:PageArea><ofd:PhysicalBox>0 0 210 297</ofd:PhysicalBox></ofd:PageArea></ofd:CommonData>'
            . '<ofd:Pages><ofd:Page ID="0" BaseLoc="Pages/Page_0/Content.xml"/></ofd:Pages></ofd:Document>');
        $zip->addFromString('Doc_0/Pages/Page_0/Content.xml', '<?xml version="1.0" encoding="UTF-8"?>'
            . '<ofd:Page xmlns:ofd="http://www.ofdspec.org/2016"><ofd:Area><ofd:PhysicalBox>0 0 210 297</ofd:PhysicalBox></ofd:Area>'
            . '<ofd:Content><ofd:Layer>' . $text . '</ofd:Layer></ofd:Content></ofd:Page>');
        $zip->close();

        $bytes = file_get_contents($tmp);
        @unlink($tmp);
        return $bytes === false ? null : $bytes;
    }

    /**
     * 生成一个最小可读 PDF（Helvetica，纯 ASCII），避免为假实现引入额外依赖。
     */
    private function pdf(array $lines): string
    {
        $content = "BT\n/F1 11 Tf\n14 TL\n50 780 Td\n";
        foreach ($lines as $line) {
            $escaped = str_replace(['\\', '(', ')'], ['\\\\', '\\(', '\\)'], $line);
            $content .= '(' . $escaped . ") Tj\nT*\n";
        }
        $content .= "ET\n";

        $objects = [
            '<< /Type /Catalog /Pages 2 0 R >>',
            '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
            '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
            '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
            '<< /Length ' . strlen($content) . " >>\nstream\n" . $content . "endstream",
        ];

        $pdf = "%PDF-1.4\n";
        $offsets = [];
        foreach ($objects as $i => $obj) {
            $offsets[$i] = strlen($pdf);
            $pdf .= ($i + 1) . " 0 obj\n" . $obj . "\nendobj\n";
        }
        $xref = strlen($pdf);
        $pdf .= "xref\n0 " . (count($objects) + 1) . "\n0000000000 65535 f \n";
        foreach ($offsets as $offset) {
            $pdf .= str_pad((string) $offset, 10, '0', STR_PAD_LEFT) . " 00000 n \n";
        }
        $pdf .= "trailer\n<< /Size " . (count($objects) + 1) . " /Root 1 0 R >>\nstartxref\n" . $xref . "\n%%EOF";
        return $pdf;
    }
}
